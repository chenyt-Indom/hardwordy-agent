"""数字人 v3 —— 音素驱动的口型合成（CPU 可跑，无神经网络推理）

## 为什么重写

旧链路（avatar2.py）的驱动源是**声学特征**：RMS 能量 + 过零率 + 谱质心
→ 一个 openness + 一个 width。它有三个原理性缺陷：

  1. 不懂语义。「爸爸」（双唇闭合）和「大大」（舌尖+大张嘴）能量曲线相近，
     频谱也分不出该闭唇还是该张嘴 —— 这就是「嘴型跟字对不上」的根。
  2. 只有 2 个自由度。真人说话至少有开口、圆唇、展唇、下唇、齿露、闭唇
     六个独立维度，「乌」的撮口和「衣」的展唇在 2 维空间里表达不出来。
  3. 渲染靠「把原图唇缝像素纵向拉伸」填缝 —— 拉 4 倍就是糊和拉丝的来源，
     再用 USM 补偿锐度，边缘就成了硬接缝。

## 新链路的做法

  文本 ──拼音──> 声母/韵母 ──> 音素时间线 ──> 6 维口型参数 ──> 渲染

  · 驱动源是**文字本身**（TTS 之前就有文本），不是猜出来的声学量；
  · 韵母表按发音部位与开口度人工标定，复合韵母带内部过渡（韵头→韵腹→韵尾）；
  · 声母→韵母、字→字之间做协同发音（coarticulation）过渡，避免机械跳变；
  · 渲染用连续形变场 + 程序化口腔（暗区/上齿/舌），不再拉伸唇缝。

## 模块

  phoneme.py  文本 → 音素时间线（含拼音正字法修正）
  viseme.py   音素 → 6 维口型参数（含协同发音插值）
  render.py   口型参数 → 帧（局部形变 + 口腔合成 + 羽化）
  engine.py   编排：文本 → TTS → 对齐 → 渲染 → mp4
"""

